from docx import Document
from docx.oxml.ns import qn
from lxml import etree
import os

doc = Document("output/Hengshan_Report_v10.docx")
body_el = doc.element.body

def mp(text, bold=False, size=11, color=None, italic=False):
    p_el = etree.SubElement(body_el, qn("w:p"))
    etree.SubElement(p_el, qn("w:pPr"))
    r_el = etree.SubElement(p_el, qn("w:r"))
    rPr = etree.SubElement(r_el, qn("w:rPr"))
    if bold: etree.SubElement(rPr, qn("w:b"))
    if italic: etree.SubElement(rPr, qn("w:i"))
    sz = etree.SubElement(rPr, qn("w:sz"))
    sz.set(qn("w:val"), str(size * 2))
    if color:
        c = etree.SubElement(rPr, qn("w:color"))
        c.set(qn("w:val"), color)
    etree.SubElement(r_el, qn("w:t")).text = text

def mbr():
    p_el = etree.SubElement(body_el, qn("w:p"))
