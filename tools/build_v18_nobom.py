def tp(t, sub=""):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(t); r.bold = True; r.font.size = Pt(20); r.font.color.rgb = RGBColor(0x1A,0x1A,0x2E)
    if sub:
        p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(sub); r2.font.size = Pt(11); r2.font.color.rgb = RGBColor(0x88,0x88,0x88)
    doc.add_paragraph()
def h1(t): p = doc.add_paragraph(); r = p.add_run(t); r.bold = True; r.font.size = Pt(15); r.font.color.rgb = RGBColor(0x2D,0x6A,0x4F)
def h2(t): p = doc.add_paragraph(); r = p.add_run(t); r.bold = True; r.font.size = Pt(12); r.font.color.rgb = RGBColor(0x44,0x44,0x44)
def h3(t): p = doc.add_paragraph(); r = p.add_run(t); r.bold = True; r.font.size = Pt(10.5)
def body(t): p = doc.add_paragraph(t); p.paragraph_format.first_line_indent = Cm(0.7)
def qt(t):
    p = doc.add_paragraph(); p.paragraph_format.left_indent = Cm(1.2); p.paragraph_format.right_indent = Cm(1.2)
    r = p.add_run(t); r.italic = True; r.font.size = Pt(10); r.font.color.rgb = RGBColor(0x88,0x88,0x88)
def bul(t): doc.add_paragraph(t, style="List Bullet")
def brk(): doc.add_page_break()
def tbl(hd, rows):
    table = doc.add_table(rows=1+len(rows), cols=len(hd)); table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i,h in enumerate(hd):
        c = table.rows[0].cells[i]; c.text = h
        for p in c.paragraphs: p.paragraph_format.space_after = Pt(0)
        for r in p.runs: r.bold = True; r.font.size = Pt(7.5)
    for ri,row in enumerate(rows):
        for ci,val in enumerate(row):
            c = table.rows[ri+1].cells[ci]; c.text = str(val)
            for p in c.paragraphs: p.paragraph_format.space_after = Pt(0)

