def tp(t, sub=""):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(t); r.bold = True; r.font.size = Pt(22); r.font.color.rgb = RGBColor(0x1A,0x1A,0x2E)
